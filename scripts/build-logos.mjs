// Generates src/content/logos.generated.ts with official brand logos (SVG paths) from
// Simple Icons (CC0) for every tool named in the content files.
// Run: node scripts/build-logos.mjs   (re-run after adding tools to the content)
import * as icons from "simple-icons";
import fs from "node:fs";

const files = ["src/content/services.ts", "src/content/caseStudies.ts", "src/content/pages.ts"];
const src = files.map((f) => fs.readFileSync(f, "utf8")).join("\n");
const names = new Set();
for (const m of src.matchAll(/(?:tools|stack|items):\s*\[([^\]]*)\]/g)) for (const n of m[1].matchAll(/"([^"]+)"/g)) names.add(n[1]);

// Content name -> Simple Icons slug, where the names differ.
const alias = {
  "WhatsApp API": "whatsapp",
  "WhatsApp Business API": "whatsapp",
  BigQuery: "googlebigquery",
  "Looker Studio": "looker",
  MCP: "modelcontextprotocol",
  "Meta Lead Ads": "meta",
  "Meta Pixel": "meta",
};

const all = Object.values(icons).filter((i) => i && i.slug);
const bySlug = new Map(all.map((i) => [i.slug, i]));
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

const out = {};
const missing = [];
for (const n of [...names].sort()) {
  const hit = (alias[n] && bySlug.get(alias[n])) || all.find((i) => norm(i.title) === norm(n)) || bySlug.get(norm(n));
  if (hit) out[n] = { title: hit.title, hex: hit.hex, path: hit.path };
  else missing.push(n);
}

const body = `// AUTO-GENERATED by scripts/build-logos.mjs — do not edit by hand.
// Brand logos from Simple Icons (https://simpleicons.org, CC0). Logos remain trademarks
// of their owners and are shown to indicate the tools we work with.
// Tools without an entry here render as a text wordmark: ${missing.join(", ")}

export type Logo = { title: string; hex: string; path: string };

export const logos: Record<string, Logo> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync("src/content/logos.generated.ts", body);
console.log(`logos: ${Object.keys(out).length}, wordmark fallback: ${missing.length}`);
console.log("fallback:", missing.join(", "));
